package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/imports"
)

// harvestTarget marks a hand-written method to delete after it has been
// generated: a byte range (doc comment through closing brace) in a source file.
type harvestTarget struct {
	file       string
	start, end int
}

// generateMethods renders methods_gen.go for the renderer's dialect by
// auto-discovery and returns the hand-written methods to harvest. See the
// config's deny list for the policy. It fails when a query's parameters
// are not named after the interface signature (see misnamedParams), in every
// mode, so a renamed field cannot quietly leave a method hand-written.
func (r renderer) generateMethods(methods map[string]methodSig, root string) ([]byte, []harvestTarget, error) {
	pkgName := filepath.Base(r.d.dir)
	dir := filepath.Join(root, r.d.dir)
	existing, err := r.genFileMethods(filepath.Join(dir, "methods_gen.go"))
	if err != nil {
		return nil, nil, err
	}
	hand, pkgFuncs, err := r.handWrittenMethods(dir)
	if err != nil {
		return nil, nil, err
	}
	r.pkgFuncs = pkgFuncs

	names := make([]string, 0, len(methods))
	for name := range methods {
		names = append(names, name)
	}
	sort.Strings(names)

	// Names are checked before shapes so a drifted field is reported as the
	// cause rather than as the generated method that stopped fitting.
	var misnamed []string
	for _, name := range names {
		if !r.cfg.denied(name) {
			misnamed = append(misnamed, r.misnamedParams(name, methods[name])...)
		}
	}
	if len(misnamed) > 0 {
		return nil, nil, fmt.Errorf("query parameters are not named after the interface signature; name them with sqlc.arg(name) or @name:\n\t%s", strings.Join(misnamed, "\n\t"))
	}

	var body strings.Builder
	var harvest []harvestTarget
	for _, name := range names {
		cands := r.candidates(name, methods[name])
		hm, hasHand := hand[name]
		genNorm, isGen := existing[name]
		switch {
		case r.cfg.denied(name):
			if isGen {
				return nil, nil, fmt.Errorf("method %q is denied in the config but still present in methods_gen.go; remove it there and hand-write it", name)
			}
		case isGen:
			if len(cands) == 0 {
				return nil, nil, fmt.Errorf("method %q is in methods_gen.go but no longer fits a generatable shape; hand-write it and delete it from methods_gen.go", name)
			}
			if hasHand {
				return nil, nil, fmt.Errorf("method %q is both generated and hand-written (%s); delete the hand-written copy", name, hm.file)
			}
			// The shape a method was harvested in is the one it keeps.
			c, err := r.matchCandidate(genNorm, cands, false)
			if err != nil {
				return nil, nil, fmt.Errorf("method %q: %w", name, err)
			}
			if c == nil {
				return nil, nil, fmt.Errorf("method %q in methods_gen.go matches no generated shape; hand-write it and delete it from methods_gen.go", name)
			}
			body.WriteString("\n")
			body.WriteString(c.emit)
		case hasHand:
			c, err := r.matchCandidate(hm.norm, cands, true)
			if err != nil {
				return nil, nil, fmt.Errorf("method %q: %w", name, err)
			}
			if c == nil {
				continue
			}
			body.WriteString("\n")
			body.WriteString(c.emit)
			harvest = append(harvest, harvestTarget{file: hm.file, start: hm.start, end: hm.end})
		}
	}

	// Generated signatures may reference arbitrary imports, so a fixed allowlist
	// would miss valid repository types.
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by repo-adapter-gen. DO NOT EDIT.\n\npackage %s\n\n%s", pkgName, body.String())
	formatted, err := imports.Process(filepath.Join(dir, "methods_gen.go"), []byte(b.String()), &imports.Options{Comments: true, TabIndent: true, TabWidth: 8})
	if err != nil {
		return nil, nil, fmt.Errorf("format methods source: %w\n%s", err, b.String())
	}
	return formatted, harvest, nil
}

// matchCandidate returns the candidate whose normalized form equals norm, or
// nil. With alternates set, a candidate's accepted hand-written spellings are
// compared as well as the form it emits.
func (r renderer) matchCandidate(norm string, cands []candidate, alternates bool) (*candidate, error) {
	for i := range cands {
		forms := []string{cands[i].emit}
		if alternates {
			forms = append(forms, cands[i].match...)
		}
		for _, form := range forms {
			n, err := r.normalize(form)
			if err != nil {
				return nil, fmt.Errorf("normalize candidate: %w\n%s", err, form)
			}
			if n == norm {
				return &cands[i], nil
			}
		}
	}
	return nil, nil
}

// handMethod is a hand-written adapter method: its normalized source (for the
// structural compare) and the byte range to delete when harvested.
type handMethod struct {
	file       string
	norm       string
	start, end int
}

// handWrittenMethods returns every method with the given adapter receiver
// across the package's hand-written files (excluding _test.go and *_gen.go),
// plus the set of package-level function names those files define.
func (r renderer) handWrittenMethods(dir string) (map[string]handMethod, map[string]bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, err
	}
	out := map[string]handMethod{}
	funcs := map[string]bool{}
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || strings.HasSuffix(n, "_gen.go") {
			continue
		}
		path := filepath.Join(dir, n)
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, nil, err
		}
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
		if err != nil {
			return nil, nil, err
		}
		for _, decl := range f.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok {
				continue
			}
			if fd.Recv == nil {
				funcs[fd.Name.Name] = true
				continue
			}
			if recvTypeName(fd.Recv) != r.d.adapterType {
				continue
			}
			pos := fset.Position(fd.Pos()).Offset
			end := fset.Position(fd.End()).Offset
			start := pos
			if fd.Doc != nil {
				start = fset.Position(fd.Doc.Pos()).Offset
			}
			norm, err := r.normalize(string(src[pos:end]))
			if err != nil {
				return nil, nil, fmt.Errorf("normalize %s.%s: %w", path, fd.Name.Name, err)
			}
			out[fd.Name.Name] = handMethod{file: path, norm: norm, start: start, end: end}
		}
	}
	return out, funcs, nil
}

// genFileMethods returns the adapter methods already present in
// methods_gen.go by name with their normalized source (empty if the file does
// not exist yet).
func (r renderer) genFileMethods(path string) (map[string]string, error) {
	src, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, 0)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, decl := range f.Decls {
		fd, ok := decl.(*ast.FuncDecl)
		if !ok || recvTypeName(fd.Recv) != r.d.adapterType {
			continue
		}
		pos := fset.Position(fd.Pos()).Offset
		end := fset.Position(fd.End()).Offset
		norm, err := r.normalize(string(src[pos:end]))
		if err != nil {
			return nil, fmt.Errorf("normalize %s.%s: %w", path, fd.Name.Name, err)
		}
		out[fd.Name.Name] = norm
	}
	return out, nil
}

// applyHarvest deletes harvested methods from their hand-written files, then
// re-formats and prunes now-unused imports. Ranges within a file are removed
// back-to-front so earlier offsets stay valid.
func applyHarvest(targets []harvestTarget) error {
	byFile := map[string][]harvestTarget{}
	for _, t := range targets {
		byFile[t.file] = append(byFile[t.file], t)
	}
	files := make([]string, 0, len(byFile))
	for f := range byFile {
		files = append(files, f)
	}
	sort.Strings(files)
	for _, file := range files {
		src, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		ts := byFile[file]
		sort.Slice(ts, func(i, j int) bool { return ts[i].start > ts[j].start })
		for _, t := range ts {
			if t.start < 0 || t.end > len(src) || t.start > t.end {
				return fmt.Errorf("%s: bad harvest range [%d,%d)", file, t.start, t.end)
			}
			src = append(src[:t.start], src[t.end:]...)
		}
		out, err := imports.Process(file, src, &imports.Options{Comments: true, TabIndent: true, TabWidth: 8})
		if err != nil {
			return fmt.Errorf("format %s after harvest: %w", file, err)
		}
		if err := os.WriteFile(file, out, 0o644); err != nil {
			return err
		}
		fmt.Printf("harvested %d method(s) from %s\n", len(ts), file)
	}
	return nil
}
